def _series(start: float, n: int = 32, drift: float = 0.002, vol: float = 0.012) -> list[float]:
    values = [start]
    seed = abs(hash((start, n, drift))) % 10_000
    for i in range(n - 1):
        shock = (((seed + i * 37) % 100) / 100.0 - 0.48) * vol
        values.append(round(values[-1] * (1 + drift + shock), 4))
    return values


def candle_for(ticker: str) -> Candle:
    quote = QUOTES.get(ticker)
    start = (quote.price if quote else 100.0) * 0.92
    closes = _series(start)
    if quote:
        closes[-1] = quote.price
    stamps = [NOW - timedelta(days=len(closes) - i) for i in range(len(closes))]
    return Candle(ticker=ticker, closes=closes, timestamps=stamps)


