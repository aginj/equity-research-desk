def _infer_market(ticker: str):
    suffix = ticker.split(".")[-1] if "." in ticker else ""
    mapping = {
        "NS": "in-nse",
        "BO": "in-bse",
        "L": "uk-lse",
        "T": "jp-tse",
        "HK": "hk-hkex",
        "DE": "de-xetr",
        "TO": "ca-tsx",
        "AX": "au-asx",
        "PA": "fr-epa",
        "AS": "nl-ams",
        "KS": "kr-krx",
        "SA": "br-b3",
        "SI": "sg-sgx",
        "TW": "tw-twse",
        "SS": "cn-sse",
        "SW": "ch-six",
    }
    return get_market(mapping.get(suffix, "us"))


